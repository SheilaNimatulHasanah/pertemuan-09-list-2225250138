# Input: List berisi 6 nilai numerik
# Proses: Mengakses elemen dengan indeks positif, negatif, dan melakukan slicing
# Output: Menampilkan elemen pertama, terakhir, 3 elemen awal, dan indeks 1 sampai 3

nilai = [75, 80, 65, 90, 88, 70]
print(nilai[0])  # Elemen pertama
print(nilai[-1])  # Elemen terakhir
print(nilai[:3])  # Tiga elemen awal
print(nilai[1:4])  # Elemen indeks 1 sampai 3 (indeks 4 tidak ikut)